use std::collections::{HashMap, HashSet};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let project_dir = manifest_dir.parent().unwrap();

    let mut classes: HashMap<String, String> = HashMap::new();
    let mut class_files: HashMap<String, (PathBuf, String)> = HashMap::new();
    let mut files = Vec::new();
    collect_rs_files(project_dir, &manifest_dir, &mut files);

    for path in &files {
        if let Ok(content) = fs::read_to_string(path) {
            if let Some(class_name) = extract_godot_class_name(&content) {
                let parent_name = extract_parent_name(&content).unwrap_or_else(|| "Node".to_string());
                classes.insert(class_name.clone(), parent_name);
                class_files.insert(class_name, (path.clone(), content));
            }
        }
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let sorted_classes = topological_sort(&classes);

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("auto_classes.rs");

    let mut code = String::new();
    code.push_str("// AUTO-GENERATED BY build.rs. DO NOT EDIT MANUALLY.\n\n");

    let mut doc_registrations = String::new();
    for (idx, cls) in sorted_classes.iter().enumerate() {
        if let Some((path, content)) = class_files.get(cls) {
            let parent = classes.get(cls).cloned().unwrap_or_else(|| "Node".to_string());
            let xml = generate_class_doc_xml(path, content, cls, &parent);
            if !xml.is_empty() {
                let const_name = format!("DOC_XML_{}", idx);
                code.push_str(&format!("const {}: &str = r##\"{}\"##;\n\n", const_name, xml));
                doc_registrations.push_str(&format!("    crate::godot_ffi::register_class_doc_xml({});\n", const_name));
            }
        }
    }

    code.push_str("#[doc(hidden)]\n");
    code.push_str("pub unsafe fn register_auto_docs() {\n");
    code.push_str(&doc_registrations);
    code.push_str("}\n\n");

    code.push_str("godot_rust_classes!(\n");
    for cls in &sorted_classes {
        code.push_str(&format!("    {},\n", cls));
    }
    code.push_str(");\n");

    fs::write(&dest_path, code).expect("Failed to write auto_classes.rs");
}

fn extract_godot_class_name(content: &str) -> Option<String> {
    for line in content.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("impl") {
            let rest = rest.trim();
            if let Some(rest) = rest.strip_prefix("GodotRustClass") {
                let rest = rest.trim();
                if let Some(rest) = rest.strip_prefix("for") {
                    let rest = rest.trim();
                    let class_name: String = rest
                        .chars()
                        .take_while(|c| c.is_alphanumeric() || *c == '_')
                        .collect();
                    if !class_name.is_empty() {
                        return Some(class_name);
                    }
                }
            }
        }
    }
    None
}

fn extract_parent_name(content: &str) -> Option<String> {
    if let Some(idx) = content.find("make_class(") {
        let after = &content[idx + "make_class(".len()..];
        if let Some(comma1) = after.find(',') {
            let after_comma1 = &after[comma1 + 1..];
            if let Some(comma2) = after_comma1.find(',') {
                let after_comma2 = after_comma1[comma2 + 1..].trim();
                if let Some(quote1) = after_comma2.find('"') {
                    let after_q1 = &after_comma2[quote1 + 1..];
                    if let Some(quote2) = after_q1.find('"') {
                        return Some(after_q1[..quote2].to_string());
                    }
                }
            }
        }
    }
    None
}

fn topological_sort(classes: &HashMap<String, String>) -> Vec<String> {
    let mut sorted = Vec::new();
    let mut visited = HashSet::new();

    fn visit(
        node: &str,
        classes: &HashMap<String, String>,
        visited: &mut HashSet<String>,
        sorted: &mut Vec<String>,
    ) {
        if visited.contains(node) {
            return;
        }
        visited.insert(node.to_string());
        if let Some(parent) = classes.get(node) {
            if classes.contains_key(parent) {
                visit(parent, classes, visited, sorted);
            }
        }
        sorted.push(node.to_string());
    }

    let mut keys: Vec<String> = classes.keys().cloned().collect();
    keys.sort();

    for key in &keys {
        visit(key, classes, &mut visited, &mut sorted);
    }

    sorted
}

fn collect_rs_files(dir: &Path, manifest_dir: &Path, files: &mut Vec<PathBuf>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if name.starts_with('.') || name == "target" || path == *manifest_dir {
                    continue;
                }
                collect_rs_files(&path, manifest_dir, files);
            } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
                files.push(path);
            }
        }
    }
}

// =========================================================================
// Rust Doc Comment (//! and ///) to Godot Help XML Extraction
// =========================================================================

#[derive(Default)]
struct ParsedDoc {
    brief: String,
    description: String,
    members: Vec<MemberInfo>,
    methods: Vec<MethodInfo>,
    constants: Vec<ConstantInfo>,
}

struct MemberInfo {
    name: String,
    type_name: String,
    doc: String,
}

struct MethodInfo {
    name: String,
    return_type: Option<String>,
    params: Vec<(String, String)>,
    doc: String,
}

struct ConstantInfo {
    name: String,
    value: String,
    enum_name: Option<String>,
    doc: String,
}

fn generate_class_doc_xml(
    rs_path: &Path,
    content: &str,
    class_name: &str,
    parent_name: &str,
) -> String {
    let parsed = parse_rust_doc_comments(content, class_name);

    // Check if an existing hand-crafted .xml file exists in the same directory
    if let Some(parent_dir) = rs_path.parent() {
        let candidates = [
            format!("{}.xml", class_name),
            format!("{}.xml", to_snake_case(class_name)),
            format!("FG_{}.xml", to_snake_case(class_name).trim_start_matches("fg_")),
            format!("FGC_{}.xml", to_snake_case(class_name).trim_start_matches("fgc_")),
        ];
        for cand in &candidates {
            let cand_path = parent_dir.join(cand);
            if cand_path.exists() {
                if let Ok(xml_content) = fs::read_to_string(&cand_path) {
                    println!("cargo:rerun-if-changed={}", cand_path.display());
                    return merge_existing_xml_with_docs(&xml_content, &parsed);
                }
            }
        }
    }

    build_xml_from_scratch(class_name, parent_name, &parsed)
}

fn parse_rust_doc_comments(content: &str, class_name: &str) -> ParsedDoc {
    let mut doc = ParsedDoc::default();
    let lines: Vec<&str> = content.lines().collect();

    // 1. Module docs (//!) at the beginning of the file
    let mut module_doc_lines = Vec::new();
    for line in &lines {
        let trimmed = line.trim();
        if trimmed.starts_with("//!") {
            let doc_text = trimmed.strip_prefix("//!").unwrap().trim();
            module_doc_lines.push(doc_text.to_string());
        } else if trimmed.starts_with("#![") || trimmed.is_empty() {
            continue;
        } else {
            break;
        }
    }

    if !module_doc_lines.is_empty() {
        let mut paragraphs: Vec<String> = Vec::new();
        let mut current_para: Vec<String> = Vec::new();
        for line in module_doc_lines {
            if line.is_empty() {
                if !current_para.is_empty() {
                    paragraphs.push(current_para.join(" "));
                    current_para.clear();
                }
            } else {
                current_para.push(line);
            }
        }
        if !current_para.is_empty() {
            paragraphs.push(current_para.join(" "));
        }

        if !paragraphs.is_empty() {
            doc.brief = paragraphs[0].clone();
            if paragraphs.len() > 1 {
                doc.description = paragraphs[1..].join("\n\n");
            }
        }
    }

    // 2. Struct docs and members
    let mut doc_buf: Vec<String> = Vec::new();
    let mut in_struct = false;
    let struct_needle = format!("struct {}", class_name);

    for line in &lines {
        let s = line.trim();
        if s.starts_with("///") {
            doc_buf.push(s.strip_prefix("///").unwrap().trim().to_string());
        } else if s.contains(&struct_needle) && !s.starts_with("//") {
            let struct_doc = doc_buf.join(" ");
            if !struct_doc.is_empty() {
                if doc.brief.is_empty() {
                    doc.brief = struct_doc;
                } else if doc.description.is_empty() {
                    doc.description = struct_doc;
                } else {
                    doc.description = format!("{}\n\n{}", doc.description, struct_doc);
                }
            }
            doc_buf.clear();
            in_struct = true;
        } else if in_struct {
            if s.starts_with('}') {
                in_struct = false;
                doc_buf.clear();
            } else if s.contains(':') && !s.starts_with("//") {
                let f_decl = s.trim_end_matches(',');
                let parts: Vec<&str> = f_decl.splitn(2, ':').collect();
                let fname = parts[0].trim().trim_start_matches("pub").trim();
                let ftype = parts[1].trim();
                let fdoc = doc_buf.join(" ");
                if !fname.is_empty() && !fdoc.is_empty() {
                    doc.members.push(MemberInfo {
                        name: fname.to_string(),
                        type_name: map_rust_type_to_godot(ftype),
                        doc: fdoc,
                    });
                }
                doc_buf.clear();
            } else if !s.is_empty() && !s.starts_with("//") {
                doc_buf.clear();
            }
        } else if !s.is_empty() && !s.starts_with("//") {
            doc_buf.clear();
        }
    }

    // 3. Methods inside impl
    doc_buf.clear();
    let mut in_impl = false;
    let impl_needle = format!("impl {}", class_name);
    let impl_trait_needle = format!("impl GodotRustClass for {}", class_name);

    for line in &lines {
        let s = line.trim();
        if s.starts_with("///") {
            doc_buf.push(s.strip_prefix("///").unwrap().trim().to_string());
        } else if (s.starts_with(&impl_needle) || s.starts_with(&impl_trait_needle)) && !s.starts_with("//") {
            in_impl = true;
            doc_buf.clear();
        } else if in_impl {
            if s.starts_with("pub fn ") || s.starts_with("pub unsafe fn ") {
                let mdoc = doc_buf.join(" ");
                if !mdoc.is_empty() {
                    if let Some(m_info) = parse_method_signature(s, mdoc) {
                        doc.methods.push(m_info);
                    }
                }
                doc_buf.clear();
            } else if s.starts_with("impl ") || s.starts_with("struct ") || s.starts_with("enum ") {
                in_impl = false;
                doc_buf.clear();
            } else if !s.is_empty() && !s.starts_with("//") {
                if !s.starts_with("pub fn") && !s.starts_with("fn ") {
                    doc_buf.clear();
                }
            }
        }
    }

    // 4. Enums and constants
    doc_buf.clear();
    let mut in_enum = false;
    let mut current_enum = String::new();

    for line in &lines {
        let s = line.trim();
        if s.starts_with("///") {
            doc_buf.push(s.strip_prefix("///").unwrap().trim().to_string());
        } else if s.starts_with("pub enum ") || s.starts_with("enum ") {
            let parts: Vec<&str> = s.split_whitespace().collect();
            if let Some(pos) = parts.iter().position(|&p| p == "enum") {
                if pos + 1 < parts.len() {
                    current_enum = parts[pos + 1].trim_end_matches('{').to_string();
                    in_enum = true;
                }
            }
            doc_buf.clear();
        } else if in_enum {
            if s.starts_with('}') {
                in_enum = false;
                current_enum.clear();
                doc_buf.clear();
            } else if !s.is_empty() && !s.starts_with("//") {
                let variant_line = s.trim_end_matches(',');
                let vname = variant_line.split('=').next().unwrap().trim();
                let vval = if variant_line.contains('=') {
                    variant_line.split('=').nth(1).unwrap().trim()
                } else {
                    "0"
                };
                let vdoc = doc_buf.join(" ");
                if !vname.is_empty() && !vdoc.is_empty() {
                    doc.constants.push(ConstantInfo {
                        name: vname.to_uppercase(),
                        value: vval.to_string(),
                        enum_name: Some(current_enum.clone()),
                        doc: vdoc,
                    });
                }
                doc_buf.clear();
            }
        } else if !s.is_empty() && !s.starts_with("//") {
            doc_buf.clear();
        }
    }

    doc
}

fn parse_method_signature(line: &str, doc: String) -> Option<MethodInfo> {
    let fn_part = line.strip_prefix("pub unsafe fn ").or_else(|| line.strip_prefix("pub fn "))?;
    let paren_open = fn_part.find('(')?;
    let name = fn_part[..paren_open].trim().to_string();

    let after_paren = &fn_part[paren_open + 1..];
    let paren_close = after_paren.find(')')?;
    let params_raw = &after_paren[..paren_close];

    let mut params = Vec::new();
    for p in params_raw.split(',') {
        let p = p.trim();
        if p.is_empty() || p == "&self" || p == "&mut self" || p.starts_with("_host") || p.starts_with("host:") {
            continue;
        }
        if let Some(colon) = p.find(':') {
            let pname = p[..colon].trim().trim_start_matches("mut ").trim();
            let ptype = p[colon + 1..].trim();
            params.push((pname.to_string(), map_rust_type_to_godot(ptype)));
        }
    }

    let rest = &after_paren[paren_close + 1..];
    let return_type = if let Some(arrow) = rest.find("->") {
        let ret_raw = rest[arrow + 2..].trim().trim_end_matches('{').trim();
        Some(map_rust_type_to_godot(ret_raw))
    } else {
        None
    };

    Some(MethodInfo {
        name,
        return_type,
        params,
        doc,
    })
}

fn map_rust_type_to_godot(rust_type: &str) -> String {
    let t = rust_type.trim();
    match t {
        "bool" => "bool".to_string(),
        "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize" => "int".to_string(),
        "f32" | "f64" => "float".to_string(),
        "String" | "&str" => "String".to_string(),
        "[f32; 2]" | "Vector2" => "Vector2".to_string(),
        "[f32; 3]" | "Vector3" => "Vector3".to_string(),
        "[f32; 4]" | "Vector4" => "Vector4".to_string(),
        "[f32; 12]" | "Transform3D" => "Transform3D".to_string(),
        "Transform2D" => "Transform2D".to_string(),
        "Basis" => "Basis".to_string(),
        "Quaternion" => "Quaternion".to_string(),
        "Color" => "Color".to_string(),
        "AABB" => "AABB".to_string(),
        "NodePath" => "NodePath".to_string(),
        "GDExtensionObjectPtr" | "Object" => "Object".to_string(),
        "Vec<String>" => "PackedStringArray".to_string(),
        "Vec<u8>" => "PackedByteArray".to_string(),
        "Vec<i32>" => "PackedInt32Array".to_string(),
        "Vec<i64>" => "PackedInt64Array".to_string(),
        "Vec<f32>" => "PackedFloat32Array".to_string(),
        "Vec<Vector3>" => "PackedVector3Array".to_string(),
        _ => {
            if t.starts_with("Option<") && t.ends_with('>') {
                map_rust_type_to_godot(&t[7..t.len() - 1])
            } else if t.starts_with('&') {
                map_rust_type_to_godot(t.trim_start_matches('&').trim())
            } else {
                t.to_string()
            }
        }
    }
}

fn escape_xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn format_doc_text(text: &str, indent: &str) -> String {
    let clean = text.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;");
    let mut formatted = String::with_capacity(clean.len());
    let mut in_code = false;
    for c in clean.chars() {
        if c == '`' {
            if in_code {
                formatted.push_str("[/code]");
                in_code = false;
            } else {
                formatted.push_str("[code]");
                in_code = true;
            }
        } else {
            formatted.push(c);
        }
    }
    if in_code {
        formatted.push_str("[/code]");
    }
    formatted.lines().collect::<Vec<_>>().join(&format!("\n{}", indent))
}

fn build_xml_from_scratch(class_name: &str, parent_name: &str, doc: &ParsedDoc) -> String {
    let mut xml = String::new();
    xml.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\" ?>\n");
    xml.push_str(&format!(
        "<class name=\"{}\" inherits=\"{}\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"../class.xsd\">\n",
        escape_xml(class_name),
        escape_xml(parent_name)
    ));

    xml.push_str("\t<brief_description>\n\t\t");
    xml.push_str(&format_doc_text(&doc.brief, "\t\t"));
    xml.push_str("\n\t</brief_description>\n");

    xml.push_str("\t<description>\n\t\t");
    xml.push_str(&format_doc_text(&doc.description, "\t\t"));
    xml.push_str("\n\t</description>\n");

    xml.push_str("\t<tutorials>\n\t</tutorials>\n");

    if !doc.methods.is_empty() {
        xml.push_str("\t<methods>\n");
        for m in &doc.methods {
            xml.push_str(&format!("\t\t<method name=\"{}\">\n", escape_xml(&m.name)));
            if let Some(ref ret) = m.return_type {
                if ret != "()" && ret != "void" {
                    xml.push_str(&format!("\t\t\t<return type=\"{}\" />\n", escape_xml(ret)));
                }
            }
            for (idx, (pname, ptype)) in m.params.iter().enumerate() {
                xml.push_str(&format!(
                    "\t\t\t<param index=\"{}\" name=\"{}\" type=\"{}\" />\n",
                    idx, escape_xml(pname), escape_xml(ptype)
                ));
            }
            if !m.doc.is_empty() {
                xml.push_str("\t\t\t<description>\n\t\t\t\t");
                xml.push_str(&format_doc_text(&m.doc, "\t\t\t\t"));
                xml.push_str("\n\t\t\t</description>\n");
            }
            xml.push_str("\t\t</method>\n");
        }
        xml.push_str("\t</methods>\n");
    }

    if !doc.members.is_empty() {
        xml.push_str("\t<members>\n");
        for mem in &doc.members {
            xml.push_str(&format!(
                "\t\t<member name=\"{}\" type=\"{}\" setter=\"\" getter=\"\">\n\t\t\t",
                escape_xml(&mem.name), escape_xml(&mem.type_name)
            ));
            xml.push_str(&format_doc_text(&mem.doc, "\t\t\t"));
            xml.push_str("\n\t\t</member>\n");
        }
        xml.push_str("\t</members>\n");
    }

    if !doc.constants.is_empty() {
        xml.push_str("\t<constants>\n");
        for c in &doc.constants {
            let enum_attr = if let Some(ref e) = c.enum_name {
                format!(" enum=\"{}\"", escape_xml(e))
            } else {
                String::new()
            };
            xml.push_str(&format!(
                "\t\t<constant name=\"{}\" value=\"{}\"{}>\n\t\t\t",
                escape_xml(&c.name), escape_xml(&c.value), enum_attr
            ));
            xml.push_str(&format_doc_text(&c.doc, "\t\t\t"));
            xml.push_str("\n\t\t</constant>\n");
        }
        xml.push_str("\t</constants>\n");
    }

    xml.push_str("</class>\n");
    xml
}

fn merge_existing_xml_with_docs(xml: &str, doc: &ParsedDoc) -> String {
    // If XML already has elements, ensure any missing members or methods from doc comments are added
    let mut result = xml.to_string();

    // Inject missing members before </members> or before </class>
    if !doc.members.is_empty() {
        let mut members_to_add = String::new();
        for mem in &doc.members {
            let search_str = format!("name=\"{}\"", mem.name);
            if !result.contains(&search_str) {
                members_to_add.push_str(&format!(
                    "\t\t<member name=\"{}\" type=\"{}\" setter=\"\" getter=\"\">\n\t\t\t{}\n\t\t</member>\n",
                    escape_xml(&mem.name), escape_xml(&mem.type_name), format_doc_text(&mem.doc, "\t\t\t")
                ));
            }
        }
        if !members_to_add.is_empty() {
            if let Some(pos) = result.find("</members>") {
                result.insert_str(pos, &members_to_add);
            } else if let Some(pos) = result.find("</class>") {
                let block = format!("\t<members>\n{}\t</members>\n", members_to_add);
                result.insert_str(pos, &block);
            }
        }
    }

    // Inject missing methods before </methods> or before </class>
    if !doc.methods.is_empty() {
        let mut methods_to_add = String::new();
        for m in &doc.methods {
            let search_str = format!("name=\"{}\"", m.name);
            if !result.contains(&search_str) {
                methods_to_add.push_str(&format!("\t\t<method name=\"{}\">\n", escape_xml(&m.name)));
                if let Some(ref ret) = m.return_type {
                    if ret != "()" && ret != "void" {
                        methods_to_add.push_str(&format!("\t\t\t<return type=\"{}\" />\n", escape_xml(ret)));
                    }
                }
                for (idx, (pname, ptype)) in m.params.iter().enumerate() {
                    methods_to_add.push_str(&format!(
                        "\t\t\t<param index=\"{}\" name=\"{}\" type=\"{}\" />\n",
                        idx, escape_xml(pname), escape_xml(ptype)
                    ));
                }
                if !m.doc.is_empty() {
                    methods_to_add.push_str(&format!("\t\t\t<description>\n\t\t\t\t{}\n\t\t\t</description>\n", format_doc_text(&m.doc, "\t\t\t\t")));
                }
                methods_to_add.push_str("\t\t</method>\n");
            }
        }
        if !methods_to_add.is_empty() {
            if let Some(pos) = result.find("</methods>") {
                result.insert_str(pos, &methods_to_add);
            } else if let Some(pos) = result.find("</class>") {
                let block = format!("\t<methods>\n{}\t</methods>\n", methods_to_add);
                result.insert_str(pos, &block);
            }
        }
    }

    result
}

fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                result.push('_');
            }
            result.push(c.to_ascii_lowercase());
        } else {
            result.push(c);
        }
    }
    result
}
